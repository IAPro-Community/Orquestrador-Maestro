/**
 * Token usage with provenance hierarchy.
 * @module tokens
 */

/** How the token counts were obtained. */
export enum TokenSource {
  /** Reported by the model provider API response. */
  ProviderReported = 'provider-reported',
  /** Collected natively by OpenCode session tracking. */
  OpenCodeNative = 'opencode-native',
  /** Derived from session file parsing heuristics. */
  SessionDerived = 'session-derived',
  /** Counted with a local tokenizer (exact match). */
  TokenizerExact = 'tokenizer-exact',
  /** Estimated via tiktoken or similar approximation. */
  TokenizerEstimated = 'tokenizer-estimated',
  /** No token data available. */
  Unavailable = 'unavailable',
}

/** Confidence level for the reported token counts. */
export enum TokenConfidence {
  /** Provider-reported or tokenizer-exact; no uncertainty. */
  Exact = 'exact',
  /** Derived from session logs with high reliability. */
  Reliable = 'reliable',
  /** Estimated or approximated; may drift from actual. */
  Estimated = 'estimated',
  /** No meaningful token data. */
  Unavailable = 'unavailable',
}

/**
 * Normalised token usage record.
 *
 * Every numeric field is `number | null` — `null` means the provider
 * did not report that counter.  `total` is a derived convenience
 * field (`input + output + reasoning`) and may also be `null` when
 * the source is {@link TokenSource.Unavailable}.
 */
export interface TokenUsage {
  /** Tokens consumed by the prompt / input. */
  inputTokens: number | null;
  /** Tokens generated by the model as completion. */
  outputTokens: number | null;
  /** Tokens used for internal reasoning / chain-of-thought. */
  reasoningTokens: number | null;
  /** Tokens served from the prompt cache (read). */
  cacheReadTokens: number | null;
  /** Tokens written into the prompt cache. */
  cacheWriteTokens: number | null;
  /** Convenience sum of input + output + reasoning. */
  total: number | null;
  /** Provenance of these numbers. */
  source: TokenSource;
  /** Confidence level for these numbers. */
  confidence: TokenConfidence;
  /** Reference to the raw evidence artifact (e.g. path to session file). */
  rawEvidenceRef?: string;
}
